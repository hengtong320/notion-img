#!/usr/bin/env node
/**
 * 构建前的纯 Node 校验器：验证四象共 72 根纹线的依赖图、完整求解序列和箭头末段方向。
 * Creator 运行时还会再次执行同样的断言。
 */
const zoneIds = ['dragon', 'tiger', 'bird', 'tortoise'];
const template = [
  ['oR', [], [0,1], [[112,-96],[112,96]]],
  ['oT', [], [-1,0], [[96,112],[-96,112]]],
  ['oL', [], [0,-1], [[-112,96],[-112,-96]]],
  ['oB', [], [1,0], [[-96,-112],[96,-112]]],
  ['mR', ['oR'], [1,0], [[34,70],[78,70],[78,-42],[92,-42],[92,48],[100,48]]],
  ['mT', ['oT'], [0,1], [[-70,34],[-70,78],[42,78],[42,92],[-48,92],[-48,100]]],
  ['mL', ['oL'], [-1,0], [[-34,-70],[-78,-70],[-78,42],[-92,42],[-92,-48],[-100,-48]]],
  ['mB', ['oB'], [0,-1], [[70,-34],[70,-78],[-42,-78],[-42,-92],[48,-92],[48,-100]]],
  ['iR', ['mR'], [1,0], [[8,52],[52,52],[52,-20],[66,-20],[66,20],[74,20]]],
  ['iT', ['mT'], [0,1], [[-52,8],[-52,52],[20,52],[20,66],[-20,66],[-20,74]]],
  ['iL', ['mL'], [-1,0], [[-8,-52],[-52,-52],[-52,20],[-66,20],[-66,-20],[-74,-20]]],
  ['iB', ['mB'], [0,-1], [[52,-8],[52,-52],[-20,-52],[-20,-66],[20,-66],[20,-74]]],
  ['cR', ['iR'], [1,0], [[-28,31],[20,31],[20,0],[46,0]]],
  ['cT', ['iT'], [0,1], [[-31,-28],[-31,20],[0,20],[0,46]]],
  ['cL', ['iL'], [-1,0], [[28,-31],[-20,-31],[-20,0],[-46,0]]],
  ['cB', ['iB'], [0,-1], [[31,28],[31,-20],[0,-20],[0,-46]]],
  ['sH', ['cR'], [1,0], [[-18,8],[18,8]]],
  ['sV', ['cB'], [0,-1], [[0,18],[0,-18]]],
];

let pieces = 0;
for (const zone of zoneIds) {
  const active = new Set(template.map(([key]) => `${zone}-${key}`));
  for (const [key, blockers, exit, points] of template) {
    const id = `${zone}-${key}`;
    const remaining = blockers.map(b => `${zone}-${b}`).filter(b => active.has(b));
    if (remaining.length) throw new Error(`${id} 仍被 ${remaining.join(',')} 阻挡`);
    const a = points.at(-2), b = points.at(-1);
    const dx = b[0]-a[0], dy=b[1]-a[1], length=Math.hypot(dx,dy)||1;
    const dot = dx/length*exit[0] + dy/length*exit[1];
    if (dot < .999) throw new Error(`${id} 箭头与末段未对齐: ${dot}`);
    active.delete(id);
    pieces++;
  }
  if (active.size) throw new Error(`${zone} 求解后仍剩余 ${active.size} 根`);
}
if (pieces !== 72) throw new Error(`纹线数量错误: ${pieces}`);
console.log(`✓ 四象归真关卡验证通过：${pieces} 根纹线，4 个象限，完整拓扑解，无死关。`);
